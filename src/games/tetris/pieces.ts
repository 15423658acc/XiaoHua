/**
 * 俄罗斯方块定义 —— 7 种标准方块（I/O/T/S/Z/J/L）
 *
 * 每种方块包含 4 个旋转状态（0°/90°/180°/270°，按顺时针），
 * 每个状态是一个 NxN 的二维矩阵，1 表示该格被填充。
 *
 * 旋转中心取矩阵中心，与 SRS 不完全一致，但行为直观、可玩。
 */

